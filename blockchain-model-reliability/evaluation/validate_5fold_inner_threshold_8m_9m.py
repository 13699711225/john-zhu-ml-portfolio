"""
Stratified 5-fold validation with inner validation threshold selection.

Core purpose
============
This script validates whether Ethereum behavioural probability mapping is
stable under held-out evaluation.

It replaces simple single-split validation with:

    Outer Stratified 5-Fold CV
        -> held-out test fold

    Inner Stratified train/validation split inside each outer train fold
        -> fit model on inner-train
        -> choose threshold on inner-validation only
        -> evaluate selected threshold on outer-test

Important constraints
=====================

1. Threshold selection MUST NOT use the test fold.
   The test fold is used only once for final evaluation.

2. Positive labels are scarce.
   Therefore, stratified folds are used to keep positive/negative balance
   in every fold as much as possible.

3. M2 Behaviour-only logistic is NOT Platt calibration.
   It is a target-domain Ethereum behavioural probability mapping baseline.

4. M3 Raw + Behaviour tests whether frozen Bitcoin raw_score adds value
   after controlling for Ethereum behaviour features.

5. If M2 ≈ M3, recovery is mainly driven by Ethereum behaviour covariates,
   not by frozen Bitcoin raw_score.

6. M4 weighted model is a robustness check only.
   If Brier/ECE degrade, it should not be treated as the main method.

Expected input
==============
A probability/feature file generated by your earlier M1-M4 script:

    m1_m4_random_probs_8m_9m.csv
    m1_m4_highconf_probs_8m_9m.csv
    m1_m4_activitymatched_probs_8m_9m.csv

Required columns:
    address
    label
    raw_prob
    log_tx_count
    log_unique_counterparties
    log_active_blocks
    log_total_amount
    contract_touch_ratio
    in_out_ratio

Models
======
V0 Frozen raw:
    raw_score without calibration.

M1 Raw-only Platt:
    input = raw_score.

M2 Behaviour-only logistic:
    input = Ethereum behaviour covariates only.

M3 Raw + Behaviour:
    input = raw_score + Ethereum behaviour covariates.

M4 Weighted Raw + Behaviour:
    input = raw_score + Ethereum behaviour covariates + sample_weight.

Outputs
=======
Output directory:
    cv5_inner_threshold_<tag>_8m_9m/

Files:
    fold_level_metrics.csv
    cv_summary_table.csv
    pooled_test_predictions.csv
    reliability_bins.csv
    final_comparison_table.csv
    validation_config.json
"""

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    roc_auc_score,
    f1_score,
    precision_score,
    recall_score,
    brier_score_loss,
    precision_recall_curve,
)
from sklearn.model_selection import StratifiedKFold, StratifiedShuffleSplit
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler


# =========================================================
# Model definitions
# =========================================================

BEHAVIOUR_COLS = [
    "log_tx_count",
    "log_unique_counterparties",
    "log_active_blocks",
    "log_total_amount",
    "contract_touch_ratio",
    "in_out_ratio",
]

MODEL_META = {
    "V0_frozen_raw": {
        "version": "V0",
        "input": "raw_score without calibration",
        "purpose": "direct transfer baseline",
    },
    "M1_raw_only_platt": {
        "version": "M1",
        "input": "raw_score",
        "purpose": "ordinary calibration baseline",
    },
    "M2_behaviour_only_logistic": {
        "version": "M2",
        "input": "behaviour covariates only",
        "purpose": "Ethereum behaviour explanatory baseline",
    },
    "M3_raw_plus_behaviour": {
        "version": "M3",
        "input": "raw_score + behaviour covariates",
        "purpose": "behaviour-aware calibration",
    },
    "M4_weighted_raw_plus_behaviour": {
        "version": "M4",
        "input": "raw_score + behaviour + sample_weight",
        "purpose": "robustness check",
    },
}


# =========================================================
# Metrics
# =========================================================

def best_threshold_on_validation(y_val, p_val):
    precision, recall, thresholds = precision_recall_curve(y_val, p_val)

    if len(thresholds) == 0:
        return 0.5, 0.0

    f1s = np.where(
        (precision[:-1] + recall[:-1]) > 0,
        2 * precision[:-1] * recall[:-1] /
        (precision[:-1] + recall[:-1] + 1e-12),
        0.0,
    )

    idx = int(np.argmax(f1s))

    return float(thresholds[idx]), float(f1s[idx])


def best_threshold_f1_test_only_for_diagnostic(y_true, probs):
    precision, recall, thresholds = precision_recall_curve(y_true, probs)

    if len(thresholds) == 0:
        return 0.0, 0.5

    f1s = np.where(
        (precision[:-1] + recall[:-1]) > 0,
        2 * precision[:-1] * recall[:-1] /
        (precision[:-1] + recall[:-1] + 1e-12),
        0.0,
    )

    idx = int(np.argmax(f1s))

    return float(f1s[idx]), float(thresholds[idx])


def compute_ece(y_true, probs, n_bins=10):
    y_true = np.asarray(y_true)
    probs = np.asarray(probs)

    bins = np.linspace(0, 1, n_bins + 1)
    ece = 0.0
    rows = []
    n = len(y_true)

    for i in range(n_bins):
        lo = bins[i]
        hi = bins[i + 1]

        if i == n_bins - 1:
            mask = (probs >= lo) & (probs <= hi)
        else:
            mask = (probs >= lo) & (probs < hi)

        count = int(mask.sum())

        if count == 0:
            rows.append({
                "bin": i,
                "bin_lo": lo,
                "bin_hi": hi,
                "count": 0,
                "avg_pred": np.nan,
                "observed_rate": np.nan,
                "abs_gap": np.nan,
            })
            continue

        avg_pred = float(probs[mask].mean())
        observed = float(y_true[mask].mean())
        gap = abs(avg_pred - observed)

        ece += (count / n) * gap

        rows.append({
            "bin": i,
            "bin_lo": lo,
            "bin_hi": hi,
            "count": count,
            "avg_pred": avg_pred,
            "observed_rate": observed,
            "abs_gap": gap,
        })

    return float(ece), rows


def evaluate_test(y_test, p_test, selected_threshold, n_bins):
    pred_selected = (p_test >= selected_threshold).astype(int)
    pred_05 = (p_test >= 0.5).astype(int)

    out = {}

    try:
        out["auc"] = float(roc_auc_score(y_test, p_test))
    except Exception:
        out["auc"] = np.nan

    try:
        out["auc_reversed"] = float(roc_auc_score(y_test, 1 - p_test))
    except Exception:
        out["auc_reversed"] = np.nan

    out["selected_threshold"] = float(selected_threshold)

    out["f1_selected_threshold"] = float(
        f1_score(y_test, pred_selected, zero_division=0)
    )
    out["precision_selected_threshold"] = float(
        precision_score(y_test, pred_selected, zero_division=0)
    )
    out["recall_selected_threshold"] = float(
        recall_score(y_test, pred_selected, zero_division=0)
    )

    out["f1_at_0.5"] = float(f1_score(y_test, pred_05, zero_division=0))
    out["precision_at_0.5"] = float(
        precision_score(y_test, pred_05, zero_division=0)
    )
    out["recall_at_0.5"] = float(
        recall_score(y_test, pred_05, zero_division=0)
    )

    f1_best_test, test_best_threshold = best_threshold_f1_test_only_for_diagnostic(
        y_test, p_test
    )
    out["f1_best_test_diagnostic"] = f1_best_test
    out["test_best_threshold_diagnostic"] = test_best_threshold

    try:
        out["brier"] = float(brier_score_loss(y_test, p_test))
    except Exception:
        out["brier"] = np.nan

    ece, _ = compute_ece(y_test, p_test, n_bins=n_bins)
    out["ece"] = ece

    return out


# =========================================================
# Input matrices
# =========================================================

def get_model_matrix(df, model):
    raw = df["raw_prob"].values.reshape(-1, 1)

    behaviour = (
        df[BEHAVIOUR_COLS]
        .replace([np.inf, -np.inf], np.nan)
        .fillna(0.0)
        .values
    )

    if model == "M1_raw_only_platt":
        return raw

    if model == "M2_behaviour_only_logistic":
        return behaviour

    if model in ["M3_raw_plus_behaviour", "M4_weighted_raw_plus_behaviour"]:
        return np.column_stack([raw, behaviour])

    raise ValueError(f"Unknown model: {model}")


def make_logistic_model():
    return Pipeline([
        ("scaler", StandardScaler()),
        ("lr", LogisticRegression(
            C=1e6,
            solver="lbfgs",
            max_iter=3000,
        )),
    ])


# =========================================================
# Sample weighting for M4
# =========================================================

def make_activity_score(df):
    cols = [
        "log_tx_count",
        "log_unique_counterparties",
        "log_active_blocks",
        "log_total_amount",
    ]

    X = (
        df[cols]
        .replace([np.inf, -np.inf], np.nan)
        .fillna(0.0)
        .values
    )

    if len(X) <= 1:
        return np.zeros(len(X))

    z = StandardScaler().fit_transform(X)

    return (
        0.35 * z[:, 0]
        + 0.30 * z[:, 1]
        + 0.20 * z[:, 2]
        + 0.15 * z[:, 3]
    )


def compute_sample_weights(y_train, df_train):
    tmp = df_train.copy()
    tmp["label"] = y_train
    tmp["activity_score"] = make_activity_score(tmp)

    try:
        tmp["activity_bucket"] = pd.qcut(
            tmp["activity_score"],
            q=min(5, max(2, len(tmp) // 5)),
            labels=False,
            duplicates="drop",
        )
    except Exception:
        tmp["activity_bucket"] = 0

    n = len(tmp)
    n_pos = max(1, int((tmp["label"] == 1).sum()))
    n_neg = max(1, int((tmp["label"] == 0).sum()))

    class_weight_pos = n / (2.0 * n_pos)
    class_weight_neg = n / (2.0 * n_neg)

    pos_dist = tmp[tmp["label"] == 1]["activity_bucket"].value_counts(normalize=True)
    neg_dist = tmp[tmp["label"] == 0]["activity_bucket"].value_counts(normalize=True)

    weights = []

    for _, row in tmp.iterrows():
        bucket = row["activity_bucket"]

        p_pos = float(pos_dist.get(bucket, 0.0))
        p_neg = float(neg_dist.get(bucket, 0.0))

        activity_weight = (p_pos + 1e-3) / (p_neg + 1e-3)
        class_weight = class_weight_pos if row["label"] == 1 else class_weight_neg

        weights.append(class_weight * activity_weight)

    return np.clip(np.asarray(weights, dtype=float), 0.1, 20.0)


# =========================================================
# CV logic
# =========================================================

def make_inner_split(y_outer_train, inner_val_size, seed):
    splitter = StratifiedShuffleSplit(
        n_splits=1,
        test_size=inner_val_size,
        random_state=seed,
    )

    train_idx, val_idx = next(
        splitter.split(np.zeros(len(y_outer_train)), y_outer_train)
    )

    return train_idx, val_idx


def run_cv(df, n_splits, inner_val_size, n_bins, seed):
    y = df["label"].astype(int).values
    raw = df["raw_prob"].values

    outer = StratifiedKFold(
        n_splits=n_splits,
        shuffle=True,
        random_state=seed,
    )

    fold_rows = []
    prediction_rows = []

    models = [
        "V0_frozen_raw",
        "M1_raw_only_platt",
        "M2_behaviour_only_logistic",
        "M3_raw_plus_behaviour",
        "M4_weighted_raw_plus_behaviour",
    ]

    for fold_id, (outer_train_idx, test_idx) in enumerate(
        outer.split(np.zeros(len(y)), y),
        start=1,
    ):
        y_outer_train = y[outer_train_idx]
        y_test = y[test_idx]

        inner_train_local, val_local = make_inner_split(
            y_outer_train=y_outer_train,
            inner_val_size=inner_val_size,
            seed=seed + fold_id * 100,
        )

        inner_train_idx = outer_train_idx[inner_train_local]
        val_idx = outer_train_idx[val_local]

        for model in models:
            if model == "V0_frozen_raw":
                p_val = raw[val_idx]
                p_test = raw[test_idx]

            else:
                X_all = get_model_matrix(df, model)
                X_train = X_all[inner_train_idx]
                X_val = X_all[val_idx]
                X_test = X_all[test_idx]

                y_train = y[inner_train_idx]

                clf = make_logistic_model()

                if model == "M4_weighted_raw_plus_behaviour":
                    weights = compute_sample_weights(
                        y_train,
                        df.iloc[inner_train_idx].reset_index(drop=True),
                    )
                    clf.fit(X_train, y_train, lr__sample_weight=weights)
                else:
                    clf.fit(X_train, y_train)

                p_val = clf.predict_proba(X_val)[:, 1]
                p_test = clf.predict_proba(X_test)[:, 1]

            selected_threshold, val_f1 = best_threshold_on_validation(
                y[val_idx],
                p_val,
            )

            metrics = evaluate_test(
                y_test=y_test,
                p_test=p_test,
                selected_threshold=selected_threshold,
                n_bins=n_bins,
            )

            row = {
                "fold": fold_id,
                "model": model,
                "version": MODEL_META[model]["version"],
                "input": MODEL_META[model]["input"],
                "purpose": MODEL_META[model]["purpose"],
                "n_train_inner": int(len(inner_train_idx)),
                "n_val_inner": int(len(val_idx)),
                "n_test": int(len(test_idx)),
                "n_test_positive": int((y_test == 1).sum()),
                "n_test_negative": int((y_test == 0).sum()),
                "validation_f1_at_selected_threshold": float(val_f1),
                **metrics,
            }

            fold_rows.append(row)

            for addr, yy, pp in zip(
                df.iloc[test_idx]["address"].values,
                y_test,
                p_test,
            ):
                prediction_rows.append({
                    "fold": fold_id,
                    "model": model,
                    "version": MODEL_META[model]["version"],
                    "address": addr,
                    "label": int(yy),
                    "prob": float(pp),
                    "selected_threshold": float(selected_threshold),
                })

    return pd.DataFrame(fold_rows), pd.DataFrame(prediction_rows)


# =========================================================
# Aggregation
# =========================================================

def summarize_folds(fold_df):
    metrics = [
        "auc",
        "auc_reversed",
        "f1_selected_threshold",
        "precision_selected_threshold",
        "recall_selected_threshold",
        "f1_at_0.5",
        "f1_best_test_diagnostic",
        "selected_threshold",
        "brier",
        "ece",
    ]

    rows = []

    for model, g in fold_df.groupby("model"):
        row = {
            "version": MODEL_META[model]["version"],
            "model": model,
            "input": MODEL_META[model]["input"],
            "purpose": MODEL_META[model]["purpose"],
            "n_folds": int(len(g)),
        }

        for m in metrics:
            vals = g[m].dropna().values
            row[f"{m}_mean"] = float(np.mean(vals)) if len(vals) else np.nan
            row[f"{m}_std"] = float(np.std(vals)) if len(vals) else np.nan
            row[f"{m}_median"] = float(np.median(vals)) if len(vals) else np.nan

        rows.append(row)

    out = pd.DataFrame(rows)

    order = ["V0", "M1", "M2", "M3", "M4"]
    out["version_order"] = out["version"].map({v: i for i, v in enumerate(order)})
    out = out.sort_values("version_order").drop(columns=["version_order"])

    return out


def build_pooled_reliability(pred_df, n_bins):
    rows = []

    for model, g in pred_df.groupby("model"):
        y = g["label"].astype(int).values
        p = g["prob"].astype(float).values

        ece, bins = compute_ece(y, p, n_bins=n_bins)

        for b in bins:
            b.update({
                "model": model,
                "version": MODEL_META[model]["version"],
                "pooled_ece": ece,
            })
            rows.append(b)

    return pd.DataFrame(rows)


def build_final_comparison(summary_df):
    keep = [
        "version",
        "model",
        "input",
        "purpose",
        "auc_mean",
        "auc_std",
        "f1_selected_threshold_mean",
        "f1_selected_threshold_std",
        "selected_threshold_mean",
        "selected_threshold_std",
        "f1_at_0.5_mean",
        "f1_best_test_diagnostic_mean",
        "brier_mean",
        "brier_std",
        "ece_mean",
        "ece_std",
    ]

    return summary_df[keep].copy()


# =========================================================
# Main
# =========================================================

def main():
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--probs-file",
        required=True,
        help="Input m1_m4_*_probs_8m_9m.csv file.",
    )
    parser.add_argument(
        "--tag",
        required=True,
        help="Output tag: random, highconf, activitymatched.",
    )
    parser.add_argument(
        "--n-splits",
        type=int,
        default=5,
        help="Outer stratified CV folds.",
    )
    parser.add_argument(
        "--inner-val-size",
        type=float,
        default=0.25,
        help="Validation size inside outer train fold.",
    )
    parser.add_argument(
        "--n-bins",
        type=int,
        default=10,
        help="ECE / reliability bins.",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
    )

    args = parser.parse_args()

    probs_file = Path(args.probs_file)
    out_dir = Path(f"cv5_inner_threshold_{args.tag}_8m_9m")
    out_dir.mkdir(parents=True, exist_ok=True)

    df = pd.read_csv(probs_file)

    required = ["address", "label", "raw_prob"] + BEHAVIOUR_COLS
    missing = [c for c in required if c not in df.columns]

    if missing:
        raise ValueError(f"Missing columns: {missing}")

    df["label"] = df["label"].astype(int)

    print("=" * 80)
    print("Stratified 5-fold CV + inner validation threshold selection")
    print("=" * 80)
    print(f"[Input] {probs_file}")
    print(f"[Output] {out_dir}")
    print(f"[Data] rows={len(df):,}, positives={(df['label']==1).sum():,}, negatives={(df['label']==0).sum():,}")
    print(f"[CV] n_splits={args.n_splits}, inner_val_size={args.inner_val_size}")
    print("=" * 80)

    fold_df, pred_df = run_cv(
        df=df,
        n_splits=args.n_splits,
        inner_val_size=args.inner_val_size,
        n_bins=args.n_bins,
        seed=args.seed,
    )

    summary_df = summarize_folds(fold_df)
    reliability_df = build_pooled_reliability(pred_df, n_bins=args.n_bins)
    final_table = build_final_comparison(summary_df)

    fold_df.to_csv(out_dir / "fold_level_metrics.csv", index=False)
    pred_df.to_csv(out_dir / "pooled_test_predictions.csv", index=False)
    summary_df.to_csv(out_dir / "cv_summary_table.csv", index=False)
    reliability_df.to_csv(out_dir / "reliability_bins.csv", index=False)
    final_table.to_csv(out_dir / "final_comparison_table.csv", index=False)

    config = {
        "input_file": str(probs_file),
        "tag": args.tag,
        "validation_design": "Outer stratified 5-fold CV with inner validation threshold selection.",
        "threshold_rule": "Threshold is selected on inner validation fold only, never on the outer test fold.",
        "models": MODEL_META,
        "constraints": {
            "M2_is_not_Platt": True,
            "M2_is_behaviour_only_probability_mapping": True,
            "M3_tests_raw_score_extra_contribution": True,
            "M4_is_robustness_check": True,
            "probability_target": "OFAC-style high-risk label under current negative definition.",
        },
        "params": {
            "n_splits": args.n_splits,
            "inner_val_size": args.inner_val_size,
            "n_bins": args.n_bins,
            "seed": args.seed,
        },
    }

    with open(out_dir / "validation_config.json", "w") as f:
        json.dump(config, f, indent=2, ensure_ascii=False)

    print("\n[Final comparison table]")
    print(final_table.to_string(index=False))

    print("\n[Saved]")
    print(f"  {out_dir / 'fold_level_metrics.csv'}")
    print(f"  {out_dir / 'pooled_test_predictions.csv'}")
    print(f"  {out_dir / 'cv_summary_table.csv'}")
    print(f"  {out_dir / 'reliability_bins.csv'}")
    print(f"  {out_dir / 'final_comparison_table.csv'}")
    print(f"  {out_dir / 'validation_config.json'}")
    print("Done.")


if __name__ == "__main__":
    main()